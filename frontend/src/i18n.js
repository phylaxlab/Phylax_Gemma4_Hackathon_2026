const listeners = new Set();

function detectLanguage() {
  const browserLang = String(navigator.language || 'en').toLowerCase();
  if (browserLang.startsWith('zh')) return 'zh';
  if (browserLang.startsWith('es')) return 'es';
  if (browserLang.startsWith('fr')) return 'fr';
  if (browserLang.startsWith('ja')) return 'ja';
  if (browserLang.startsWith('ko')) return 'ko';
  return 'en';
}

function readStoredLanguage() {
  try {
    const stored = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
    return LANGUAGE_META[stored] ? stored : null;
  } catch {
    return null;
  }
}

let currentLanguage = readStoredLanguage() || detectLanguage();

function writeStoredLanguage(language) {
  try {
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
  } catch {
    // Ignore persistence issues.
  }
}

function applyDocumentLanguage(language) {
  const locale = LANGUAGE_META[language]?.locale || LANGUAGE_META.en.locale;
  document.documentElement.lang = locale;
}

function resolvePath(object, path) {
  return path.split('.').reduce((value, key) => (value == null ? undefined : value[key]), object);
}

function interpolate(template, vars = {}) {
  if (typeof template !== 'string') return template;
  return template.replace(/\{\{(\w+)\}\}/g, (_, key) => {
    const value = vars[key];
    return value == null ? '' : String(value);
  });
}

function getMessages(language) {
  return translations[language] || translations.en;
}

export function getLanguage() {
  return currentLanguage;
}

export function getLocale() {
  return LANGUAGE_META[currentLanguage]?.locale || LANGUAGE_META.en.locale;
}

export function getSupportedLanguages() {
  return Object.entries(LANGUAGE_META).map(([code, meta]) => ({
    code,
    label: meta.label,
  }));
}

export function setLanguage(language) {
  if (!LANGUAGE_META[language] || language === currentLanguage) {
    return;
  }
  currentLanguage = language;
  writeStoredLanguage(language);
  applyDocumentLanguage(language);
  listeners.forEach((listener) => listener(language));
}

export function subscribeLanguage(listener) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export function t(path, vars = {}) {
  const localized = resolvePath(getMessages(currentLanguage), path);
  const fallback = resolvePath(translations.en, path);
  const template = localized == null ? fallback : localized;
  if (Array.isArray(template)) return template.slice();
  if (template == null) return path;
  return interpolate(template, vars);
}

export function tList(path) {
  const value = t(path);
  return Array.isArray(value) ? value : [];
}

export function formatNumber(value) {
  return new Intl.NumberFormat(getLocale()).format(Number(value || 0));
}

export function formatTimeOfDay(timestampSec) {
  if (!Number.isFinite(Number(timestampSec))) return t('common.unknown');
  return new Date(Number(timestampSec) * 1000).toLocaleTimeString(getLocale(), {
    hour: '2-digit',
    minute: '2-digit',
    second: '2-digit',
  });
}

export function formatVideoTime(sec) {
  const total = Math.max(0, Math.floor(Number(sec || 0)));
  const hours = Math.floor(total / 3600);
  const minutes = Math.floor((total % 3600) / 60);
  const seconds = total % 60;
  if (hours > 0) {
    return `${hours}:${String(minutes).padStart(2, '0')}:${String(seconds).padStart(2, '0')}`;
  }
  return `${minutes}:${String(seconds).padStart(2, '0')}`;
}

export function formatDurationClock(sec) {
  return formatVideoTime(sec);
}

export function formatRelativeTime(timestampSec) {
  const seconds = Math.max(0, Math.round((Date.now() / 1000) - Number(timestampSec || 0)));
  if (seconds < 10) {
    return t('common.justNow');
  }
  const formatter = new Intl.RelativeTimeFormat(getLocale(), {
    numeric: 'auto',
    style: 'short',
  });
  if (seconds < 60) {
    return formatter.format(-seconds, 'second');
  }
  const minutes = Math.floor(seconds / 60);
  if (minutes < 60) {
    return formatter.format(-minutes, 'minute');
  }
  const hours = Math.floor(minutes / 60);
  if (hours < 24) {
    return formatter.format(-hours, 'hour');
  }
  const days = Math.floor(hours / 24);
  if (days < 30) {
    return formatter.format(-days, 'day');
  }
  return new Date(Number(timestampSec || 0) * 1000).toLocaleDateString(getLocale());
}

export function formatRelativeClock(timestampSec) {
  const seconds = Math.max(0, Math.round((Date.now() / 1000) - Number(timestampSec || 0)));
  if (seconds < 5) {
    return t('common.now');
  }
  if (seconds < 3600) {
    const minutes = Math.floor(seconds / 60);
    const remainder = seconds % 60;
    return `${minutes}:${String(remainder).padStart(2, '0')} ${t('common.ago')}`;
  }
  return formatTimeOfDay(timestampSec);
}

